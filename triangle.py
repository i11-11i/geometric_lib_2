def area(a, h):
    '''
    Берет сторону треугольника a и высоту h, считает площадь.
    Пример вызова: area(5, 4) -> 10.0
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''
    Складывает три стороны треугольника и возвращает периметр.
    Пример вызова: perimeter(3, 4, 5) -> 12
    '''
    return a + b + c